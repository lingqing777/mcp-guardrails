def _build_single_step(records: list[dict], family: str, start_idx: int, width: int = 3) -> list[dict]:
    """Build single-step JSONL records from CHAR_INJECTION / PROMPT_INJECTION."""
    out = []
    for i, rec in enumerate(records):
        case_id = f"mbc:attack:{str(start_idx + i).zfill(width)}"
        record = {
            "case_id": case_id,
            "label": "attack",
            "family": family,
            "subcategory": rec["sub"],
            "tool": rec["tool"],
            "args": rec["args"],
            "expected_block_by": rec["block"],
            "tag": rec["tag"],
        }
        if "note" in rec:
            record["note"] = rec["note"]
        out.append(record)
    return out


def _build_multi_step(records: list[dict], start_idx: int, width: int = 3) -> list[dict]:
    out = []
    for i, rec in enumerate(records):
        case_id = f"mbc:chain:{str(start_idx + i).zfill(width)}"
        record = {
            "case_id": case_id,
            "label": "attack",
            "family": "call_chain",
            "subcategory": rec["sub"],
            "steps": rec["steps"],
            "expected_chain": rec["chain"],
            "expected_block_step": rec["step"],
            "tag": rec["tag"],
        }
        if "note" in rec:
            record["note"] = rec["note"]
        out.append(record)
    return out


def build_all() -> list[dict]:
    out: list[dict] = []
    # char_injection: mbc:attack:001..050
    out.extend(_build_single_step(CHAR_INJECTION, "char_injection", start_idx=1))
    # prompt_injection_and_priv_esc: mbc:attack:101..150
    out.extend(_build_single_step(PROMPT_INJECTION, "prompt_injection_and_priv_esc", start_idx=101))
    # call_chain: mbc:chain:001..050
    out.extend(_build_multi_step(CALL_CHAIN, start_idx=1))
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True, help="path to write attacks.jsonl")
    args = ap.parse_args(argv)
    records = build_all()
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as fh:
        for rec in records:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")

    # Dataset sanity
    n_char = sum(1 for r in records if r.get("family") == "char_injection")
    n_pi = sum(1 for r in records if r.get("family") == "prompt_injection_and_priv_esc")
    n_chain = sum(1 for r in records if r.get("family") == "call_chain")
    print(
        f"[build-mbench-attacks] wrote {len(records)} records → {out_path}",
        file=sys.stderr,
    )
    print(
        f"  char_injection: {n_char}  prompt_injection_and_priv_esc: {n_pi}  call_chain: {n_chain}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
